INC A
MOV B, #24
DIV AB
MOV A, B
MOVX @DPTR, A
RET

DISPLAY_MODE:
; At 9011H: 0 for stopwatch, 1 for clock
MOV R0, #6

MOV DPTR, #9011H
MOVX A, @DPTR
MOV R1, #10

JNZ DISPLAY_MODE_CLK

DISPLAY_MODE_SW:
MOV DPTR, #9005H
JMP DISPLAY_STOPWATCH_LOOP

DISPLAY_MODE_CLK:
MOV DPTR, #9002H

DISPLAY_STOPWATCH_LOOP:
MOVX A, @DPTR
MOV B, #10
DIV AB
MOV @R1, B
INC R1
MOV @R1, A
INC R1
DEC DPL

DJNZ R0, DISPLAY_STOPWATCH_LOOP

CALL MULTIPLEX_DISPLAYS

RET

ORG 0FFF6H ; Timer interrupts
INC 20
JMP TIMER_1S

ORG 9100H

TIMER_1S:
CLR TR1
MOV TH1, #3CH
MOV TL1, #0B0H
DJNZ 22H, TIMER_1S_CONTINUE
MOV 22H, #20
JMP TIMER_EVENT
TIMER_1S_CONTINUE:
SETB TR1
RETI

TIMER_EVENT:
CALL INCREMENT_CLOCK
MOV 16, DPH
MOV 17, DPL
MOV DPTR, #9010H
MOV 18, A
MOVX A, @DPTR
JZ TIMER_INT_NINC_SW
CALL INCREMENT_STOPWATCH
TIMER_INT_NINC_SW:
MOV A, 18
MOV DPH, 16
MOV DPL, 17
SETB TR1
RETI

ORG 8100H

MAIN:
MOV A, #70H
MOV SP, A

MOV A, #10001001B
MOV DPTR, #0E803H
MOVX @DPTR, A

MOV DPTR, #0E802H
MOV A, #0FFH
MOVX @DPTR, A

MOV 20, #0 ; TIMER_INT
MOV 21, #0
MOV 20H, #0
MOV 21H, #0

CALL RESET_STOPWATCH
CALL RESET_CLOCK

; Timer and interrupt setup
MOV TMOD, #10H
MOV TH1, #3CH
MOV TL1, #0B0H
MOV 22H, #20

SETB ET1
SETB EA
SETB TR1

ITERATE:
MOV DPTR, #0E802H
MOVX A, @DPTR
MOV 20H, A
JNB 20H.1, ITERATE_RESET_MODE
ITERATE_SET_MODE:
MOV DPTR, #9011H
MOV A, #1
MOVX @DPTR, A
JMP ITERATE_MODE_END
ITERATE_RESET_MODE:
MOV DPTR, #9011H
MOV A, #0
MOVX @DPTR, A
ITERATE_MODE_END:

JNB 20H.0, ITERATE_RESET_SW
ITERATE_SET_SW:
MOV DPTR, #9010H
MOV A, #1
MOVX @DPTR, A
JB 21H.0, ITERATE_SW_END
CALL RESET_STOPWATCH
ITERATE_SET_SW_NR:
SETB 21H.0
JMP ITERATE_SW_END
ITERATE_RESET_SW:
MOV DPTR, #9010H
MOV A, #0
MOVX @DPTR, A
CLR 21H.0
ITERATE_SW_END:

CALL DISPLAY_MODE

JMP ITERATE

END
